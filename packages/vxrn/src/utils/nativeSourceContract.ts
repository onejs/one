export interface NativeSourceMethod {
  name: string
  parameters: { name: string; label: string | null; type: string; nativeType: string }[]
  result: string
  nativeResult: string
  throws: boolean
  async: boolean
}

export interface NativeSourceModule {
  name: string
  methods: NativeSourceMethod[]
}

// a public @Composable function in a .kt file, or a non-private `struct X: View`
// in a .swift file: imported as a react component whose props are its
// parameters (kotlin) or stored properties (swift). a function-typed one is a
// callback.
export interface NativeSourceViewProp {
  name: string
  type: string
  nativeType: string
  optional: boolean
  callback: { type: string; nativeType: string }[] | null
}

export interface NativeSourceView {
  name: string
  props: NativeSourceViewProp[]
}

export interface NativeSourceContract {
  language: 'swift' | 'kotlin'
  packageName?: string
  modules: NativeSourceModule[]
  views: NativeSourceView[]
  defaultView: boolean
  hash: string
  declaration: string
}

