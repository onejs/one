// run `bun run generate:ios-types` on macos to refresh the committed sdk types.
// `--facades <dir>` emits declarations from existing facades without an sdk.
import { spawnSync } from 'node:child_process'
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
  rmSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { createRequire } from 'node:module'

const packageRoot = resolve(import.meta.dirname, '../..')
const out = join(packageRoot, 'ios-types')
const args = process.argv.slice(2)
const at = args.indexOf('--facades')
if (args.length && (at !== 0 || args.length !== 2))
  throw new Error('usage: bun run generate:ios-types [--facades <dir>]')
const scratch = mkdtempSync(join(tmpdir(), 'one-ios-types-'))
const facades = at < 0 ? join(scratch, 'facades') : resolve(args[at + 1])
try {
  if (at < 0) {
    const { sdkModules, extractGraphs } = await import('./graph')
    const { prepare, generateModule } = await import('./generate')
    const { emitFacade } = await import('./emit-ts')
    const modules = sdkModules()
    const extracted = await extractGraphs(modules)
    // twitter's deprecated module explicitly rejects swift imports.
    const failures = extracted.failed.filter(({ module }) => module !== 'Twitter')
    if (failures.length) throw new Error(JSON.stringify(failures))
    const prepared = prepare()
    mkdirSync(facades)
    for (let offset = 0; offset < modules.length; offset += 12) {
      for (const module of modules.slice(offset, offset + 12)) {
        if (module === 'Twitter') continue
        const result = await generateModule(module, prepared, scratch)
        if (!result || result.errors.length)
          throw new Error(
            `${module}: ${result?.errors.join('\n') ?? 'missing symbol graph'}`
          )
        writeFileSync(
          join(facades, `${module}.ts`),
          emitFacade(result.output, prepared.bridge)
        )
      }
      console.log(
        `generated ${Math.min(offset + 12, modules.length)}/${modules.length} frameworks`
      )
    }
  }
  const files = readdirSync(facades)
    .filter((file) => file.endsWith('.ts') && !file.endsWith('.d.ts'))
    .sort()
  if (!files.length) throw new Error(`no facades in ${facades}`)
  const config = join(scratch, 'tsconfig.json')
  const declarations = join(scratch, 'declarations')
  writeFileSync(
    config,
    JSON.stringify({
      compilerOptions: {
        target: 'ESNext',
        module: 'ESNext',
        moduleResolution: 'Bundler',
        declaration: true,
        emitDeclarationOnly: true,
        noCheck: true,
        types: [],
        rootDir: facades,
        outDir: declarations,
      },
      files: files.map((file) => join(facades, file)),
    })
  )
  const require = createRequire(import.meta.url)
  const compiler = join(require.resolve('typescript/package.json'), '../bin/tsc')
  const result = spawnSync(process.execPath, [compiler, '-p', config], {
    stdio: 'inherit',
  })
  if (result.status !== 0)
    throw new Error(`declaration emission failed: ${result.status}`)
  mkdirSync(out, { recursive: true })
  const expected = new Set(files.map((file) => file.replace(/\.ts$/, '.d.ts')))
  for (const file of expected) {
    const declaration = readFileSync(join(declarations, file), 'utf8')
    writeFileSync(
      join(out, file),
      `// generated by bun run generate:ios-types; do not edit\n${declaration}`
    )
  }
  for (const file of readdirSync(out))
    if (file.endsWith('.d.ts') && !expected.has(file)) rmSync(join(out, file))
  console.log(`wrote ${expected.size} frameworks to ${out}`)
} finally {
  rmSync(scratch, { recursive: true, force: true })
}
